"""
simdata/dataset_card.py — Write dataset_card.md with statistics and assumptions.

Public API
----------
write_dataset_card(df, splits, out_path, profile, sensors_cfg, scenarios_cfg)
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd

from grid.config import SensorsConfig, ScenariosConfig


def write_dataset_card(
    df: pd.DataFrame,
    splits: dict[str, list[int]],
    out_path: Path,
    profile: str,
    sensors_cfg: SensorsConfig,
    scenarios_cfg: ScenariosConfig,
) -> None:
    """Write a markdown dataset card for the generated dataset."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    label_counts = df["label"].value_counts().to_dict()
    theft_df = df[df["label"] == "theft"]

    lines = [
        "# Dataset Card — Sharavathi Corridor Synthetic Scenarios",
        "",
        "> **Auto-generated by `simdata/dataset_card.py`** — do not edit manually.",
        "> All parameter values are assumed (source: assumed) unless noted.",
        "",
        "---",
        "",
        "## 1. Overview",
        "",
        f"| Property | Value |",
        f"|----------|-------|",
        f"| Total rows | {len(df):,} |",
        f"| Total columns | {df.shape[1]} |",
        f"| Sensor profile | `{profile}` |",
        f"| Load scale range | {df['load_scale'].min():.3f} – {df['load_scale'].max():.3f} |",
        f"| Unique group IDs | {df['group_id'].nunique():,} |",
        "",
        "---",
        "",
        "## 2. Class Distribution",
        "",
        "| Label | Count | % |",
        "|-------|------:|--:|",
    ]

    for label, count in sorted(label_counts.items()):
        pct = 100.0 * count / len(df)
        lines.append(f"| `{label}` | {count:,} | {pct:.1f}% |")

    lines += [
        "",
        "---",
        "",
        "## 3. Theft Statistics",
        "",
    ]

    if len(theft_df) > 0:
        mag = theft_df["magnitude_mw"]
        km  = theft_df["true_km"].dropna()
        lines += [
            f"| Property | Value |",
            f"|----------|-------|",
            f"| Count | {len(theft_df):,} |",
            f"| Magnitude range | {mag.min():.1f} – {mag.max():.1f} MW |",
            f"| Magnitude mean | {mag.mean():.2f} MW |",
            f"| Magnitude std | {mag.std():.2f} MW |",
            f"| Location range | {km.min():.0f} – {km.max():.0f} km |",
            f"| Small theft (≤3 MW) | {(mag <= 3.0).sum():,} rows |",
            f"| Large theft (>10 MW) | {(mag > 10.0).sum():,} rows |",
        ]
    else:
        lines.append("*(no theft rows)*")

    lines += [
        "",
        "---",
        "",
        "## 4. Data Splits",
        "",
        "| Split | Rows | % of total |",
        "|-------|-----:|----------:|",
    ]
    for name, idx in splits.items():
        pct = 100.0 * len(idx) / len(df)
        lines.append(f"| `{name}` | {len(idx):,} | {pct:.1f}% |")

    lines += [
        "",
        "> **Splitting rules:**",
        "> - Split is by `group_id` — no group appears in >1 of train/val/test.",
        f"> - Leave-location-out: theft rows within ±5 km of "
        f"`{scenarios_cfg.holdout_locations_km}` go to `test_loc_holdout` only.",
        "",
        "---",
        "",
        "## 5. Sensor Configuration",
        "",
        f"| Setting | Value |",
        f"|---------|-------|",
        f"| Profile used | `{profile}` |",
        f"| vm noise | {sensors_cfg.noise.vm_pct} % of reading |",
        f"| P noise | {sensors_cfg.noise.p_pct} % of reading |",
        f"| Q noise | {sensors_cfg.noise.q_pct} % of reading |",
        f"| va noise | {sensors_cfg.noise.va_deg} degrees |",
        "",
        "---",
        "",
        "## 6. Assumptions & Known Limitations",
        "",
        "1. **All electrical parameters are assumed** (source: assumed) — not verified "
        "with KPTCL/SLDC data. See `config/topology.yaml`.",
        "2. **Chain topology only** — no meshed network, no parallel paths other than "
        "the double-circuit representation.",
        "3. **Shunt capacitors are always-on** — no tap-changer or switchable compensation. "
        "Ferranti effect causes vm > 1.05 pu at light loads.",
        "4. **Theft is modelled as a constant-power load** — no time-of-day variation in "
        "the theft behaviour within a scenario.",
        "5. **Non-converged PF cases are skipped** — these occur for extreme line outage "
        "combinations and are not represented in the dataset.",
        "6. **Sensor bias/drift magnitudes are assumed** — ranges chosen to be physically "
        "plausible for utility-grade SCADA but not calibrated to real KPTCL meters.",
        "7. **Small theft (1–3 MW) overlaps with noise** — intentional, to represent "
        "the practical sensitivity limit. Do not tune noise to artificially improve "
        "detection of small thefts.",
        "",
        "---",
        "",
        "## 7. Reproducibility",
        "",
        "Re-run with the same `--seed` to get an identical parquet (bitwise hash match):",
        "```",
        "python -m simdata.generate --profile major_only --seed 42 --out data/processed/",
        "```",
        "",
        "Verified: same seed → identical `scenario_id` ordering and measurement values.",
        "",
        "---",
        "",
        "*Generated by WF2 (`simdata/dataset_card.py`) — Sharavathi Corridor Project*",
    ]

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Dataset card saved: {out_path}")
